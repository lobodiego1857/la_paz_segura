-- La Paz Segura | Esquema inicial alineado con la propuesta aprobada.
-- Ejecutar desde Supabase SQL Editor. No contiene datos de zonas ni inspecciones.
-- IMPORTANTE: RLS protege datos aunque se intente acceder desde fuera de la interfaz.

begin;

-- M1. Perfiles de aplicación vinculados a Supabase Auth.
create table if not exists public.perfiles (
  id_usuario uuid primary key references auth.users(id) on delete cascade,
  nombre text not null check (length(btrim(nombre)) between 1 and 120),
  correo text not null unique,
  rol text not null default 'inspector' check (rol in ('administrador', 'inspector', 'consultor')),
  activo boolean not null default false,
  fecha_creacion timestamptz not null default now()
);

-- Catálogo controlado de categorías; no son diagnósticos ni niveles científicos de peligro.
create table if not exists public.tipos_riesgo (
  id_tipo_riesgo smallint generated by default as identity primary key,
  nombre text not null unique,
  descripcion text
);

-- M2. Zonas: las desactivaciones son lógicas para conservar el historial.
create table if not exists public.zonas (
  id_zona bigint generated by default as identity primary key,
  nombre text not null check (length(btrim(nombre)) between 1 and 160),
  direccion text,
  referencia text,
  id_tipo_riesgo smallint not null references public.tipos_riesgo(id_tipo_riesgo),
  latitud numeric(9,6) not null check (latitud between -90 and 90),
  longitud numeric(9,6) not null check (longitud between -180 and 180),
  descripcion text,
  activa boolean not null default true,
  fecha_registro timestamptz not null default now()
);

-- M3. El estado se cambia exclusivamente mediante la función atómica de M4.
create table if not exists public.inspecciones (
  id_inspeccion bigint generated by default as identity primary key,
  id_zona bigint not null references public.zonas(id_zona),
  id_usuario uuid not null references public.perfiles(id_usuario),
  fecha_inspeccion date not null default current_date,
  observaciones text not null check (length(btrim(observaciones)) between 1 and 10000),
  nivel_atencion text not null check (nivel_atencion in ('Baja', 'Media', 'Alta')),
  recomendaciones text,
  estado text not null default 'Pendiente' check (estado in ('Pendiente', 'En seguimiento', 'Cerrada')),
  fecha_actualizacion timestamptz not null default now()
);

-- M3. Evidencias en bucket privado `evidencias`. Máximo cinco fotos por inspección.
create table if not exists public.fotografias (
  id_fotografia bigint generated by default as identity primary key,
  id_inspeccion bigint not null references public.inspecciones(id_inspeccion),
  ruta_archivo text not null unique,
  descripcion text,
  fecha_carga timestamptz not null default now(),
  constraint ruta_archivo_corresponde_inspeccion check (
    ruta_archivo like ('inspecciones/' || id_inspeccion::text || '/%')
  )
);

-- M4. Registro cronológico de cambios/acciones. No se concede INSERT directo al cliente.
create table if not exists public.seguimientos (
  id_seguimiento bigint generated by default as identity primary key,
  id_inspeccion bigint not null references public.inspecciones(id_inspeccion),
  id_usuario uuid not null references public.perfiles(id_usuario),
  estado_nuevo text not null check (estado_nuevo in ('Pendiente', 'En seguimiento', 'Cerrada')),
  comentario text not null check (length(btrim(comentario)) between 1 and 4000),
  fecha_cambio timestamptz not null default now(),
  accion text,
  fecha_prevista date,
  resultado text
);

create index if not exists idx_zonas_tipo_activa on public.zonas(id_tipo_riesgo, activa);
create index if not exists idx_inspecciones_zona_fecha on public.inspecciones(id_zona, fecha_inspeccion desc);
create index if not exists idx_inspecciones_usuario on public.inspecciones(id_usuario);
create index if not exists idx_inspecciones_estado on public.inspecciones(estado);
create index if not exists idx_fotografias_inspeccion on public.fotografias(id_inspeccion);
create index if not exists idx_seguimientos_inspeccion_fecha on public.seguimientos(id_inspeccion, fecha_cambio desc);

-- Funciones pequeñas SECURITY DEFINER para políticas RLS sin recursión en perfiles.
create or replace function public.perfil_activo()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.perfiles p
    where p.id_usuario = auth.uid() and p.activo = true
  );
$$;

create or replace function public.tiene_rol(p_roles text[])
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.perfiles p
    where p.id_usuario = auth.uid()
      and p.activo = true
      and p.rol = any(p_roles)
  );
$$;

revoke all on function public.perfil_activo() from public, anon;
revoke all on function public.tiene_rol(text[]) from public, anon;
grant execute on function public.perfil_activo() to authenticated;
grant execute on function public.tiene_rol(text[]) to authenticated;

-- Auth registration creates a pending profile. The submitted client metadata cannot set role/active.
create or replace function public.crear_perfil_nuevo_usuario()
returns trigger
language plpgsql
security definer
set search_path = public, auth
as $$
declare
  v_nombre text;
begin
  v_nombre := coalesce(nullif(btrim(new.raw_user_meta_data ->> 'nombre'), ''), nullif(split_part(coalesce(new.email, ''), '@', 1), ''), 'Usuario');
  insert into public.perfiles (id_usuario, nombre, correo, rol, activo)
  values (new.id, v_nombre, lower(new.email), 'inspector', false)
  on conflict (id_usuario) do nothing;
  return new;
end;
$$;

revoke all on function public.crear_perfil_nuevo_usuario() from public, anon, authenticated;
drop trigger if exists on_auth_user_created_profile on auth.users;
create trigger on_auth_user_created_profile
after insert on auth.users
for each row execute function public.crear_perfil_nuevo_usuario();

-- Keep email synchronized when Supabase Auth updates it.
create or replace function public.sincronizar_correo_perfil()
returns trigger
language plpgsql
security definer
set search_path = public, auth
as $$
begin
  if new.email is distinct from old.email then
    update public.perfiles set correo = lower(new.email) where id_usuario = new.id;
  end if;
  return new;
end;
$$;
revoke all on function public.sincronizar_correo_perfil() from public, anon, authenticated;
drop trigger if exists on_auth_user_email_updated on auth.users;
create trigger on_auth_user_email_updated
after update of email on auth.users
for each row execute function public.sincronizar_correo_perfil();

-- Initial history entry is saved in the same transaction as a new inspection.
create or replace function public.registrar_inspeccion_inicial_en_historial()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.seguimientos (id_inspeccion, id_usuario, estado_nuevo, comentario, accion)
  values (new.id_inspeccion, new.id_usuario, new.estado, 'Registro inicial de la inspección.', 'Creación de inspección');
  return new;
end;
$$;
revoke all on function public.registrar_inspeccion_inicial_en_historial() from public, anon, authenticated;
drop trigger if exists on_inspeccion_created_add_history on public.inspecciones;
create trigger on_inspeccion_created_add_history
after insert on public.inspecciones
for each row execute function public.registrar_inspeccion_inicial_en_historial();

create or replace function public.actualizar_fecha_inspeccion()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.fecha_actualizacion := now();
  return new;
end;
$$;
drop trigger if exists on_inspeccion_update_timestamp on public.inspecciones;
create trigger on_inspeccion_update_timestamp
before update on public.inspecciones
for each row execute function public.actualizar_fecha_inspeccion();

-- Enforce the five-photo limit under a lock to reduce concurrent upload races.
create or replace function public.validar_maximo_fotografias()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_total integer;
begin
  perform 1 from public.inspecciones where id_inspeccion = new.id_inspeccion for update;
  select count(*) into v_total from public.fotografias where id_inspeccion = new.id_inspeccion;
  if v_total >= 5 then
    raise exception 'Una inspección admite como máximo cinco fotografías.' using errcode = 'check_violation';
  end if;
  return new;
end;
$$;
revoke all on function public.validar_maximo_fotografias() from public, anon, authenticated;
drop trigger if exists on_fotografia_check_limit on public.fotografias;
create trigger on_fotografia_check_limit
before insert on public.fotografias
for each row execute function public.validar_maximo_fotografias();

-- M4. Cambiar estado + guardar actuación en una sola operación atómica.
create or replace function public.registrar_seguimiento(
  p_id_inspeccion bigint,
  p_estado_nuevo text,
  p_comentario text,
  p_accion text default null,
  p_fecha_prevista date default null,
  p_resultado text default null
)
returns bigint
language plpgsql
security definer
set search_path = public, auth
as $$
declare
  v_usuario uuid := auth.uid();
  v_rol text;
  v_activo boolean;
  v_propietario uuid;
  v_estado_actual text;
  v_id_seguimiento bigint;
begin
  if v_usuario is null then
    raise exception 'Debes iniciar sesión.' using errcode = '28000';
  end if;

  select p.rol, p.activo into v_rol, v_activo
  from public.perfiles p where p.id_usuario = v_usuario;
  if not found or v_activo is distinct from true then
    raise exception 'La cuenta está pendiente de aprobación o desactivada.' using errcode = '42501';
  end if;
  if v_rol not in ('administrador', 'inspector') then
    raise exception 'El rol consultor solo puede consultar información.' using errcode = '42501';
  end if;
  if p_estado_nuevo not in ('Pendiente', 'En seguimiento', 'Cerrada') then
    raise exception 'Estado de seguimiento no válido.' using errcode = '22023';
  end if;
  if p_comentario is null or length(btrim(p_comentario)) = 0 then
    raise exception 'El comentario es obligatorio para registrar una actuación.' using errcode = '23514';
  end if;

  select i.id_usuario, i.estado into v_propietario, v_estado_actual
  from public.inspecciones i
  where i.id_inspeccion = p_id_inspeccion
  for update;
  if not found then
    raise exception 'No se encontró la inspección.' using errcode = 'P0002';
  end if;
  if v_rol = 'inspector' and v_propietario <> v_usuario then
    raise exception 'El inspector solo puede dar seguimiento a sus propias inspecciones.' using errcode = '42501';
  end if;
  if p_estado_nuevo = 'Cerrada' and v_rol <> 'administrador' then
    raise exception 'Solo el administrador puede cerrar una inspección.' using errcode = '42501';
  end if;
  if v_estado_actual = 'Cerrada' and p_estado_nuevo <> 'Cerrada' and v_rol <> 'administrador' then
    raise exception 'Solo el administrador puede reabrir una inspección cerrada.' using errcode = '42501';
  end if;

  update public.inspecciones
  set estado = p_estado_nuevo, fecha_actualizacion = now()
  where id_inspeccion = p_id_inspeccion;

  insert into public.seguimientos (
    id_inspeccion, id_usuario, estado_nuevo, comentario, accion, fecha_prevista, resultado
  ) values (
    p_id_inspeccion, v_usuario, p_estado_nuevo, btrim(p_comentario), nullif(btrim(p_accion), ''), p_fecha_prevista, nullif(btrim(p_resultado), '')
  ) returning id_seguimiento into v_id_seguimiento;

  return v_id_seguimiento;
end;
$$;
revoke all on function public.registrar_seguimiento(bigint, text, text, text, date, text) from public, anon;
grant execute on function public.registrar_seguimiento(bigint, text, text, text, date, text) to authenticated;

-- RLS: enabled on every application table.
alter table public.perfiles enable row level security;
alter table public.tipos_riesgo enable row level security;
alter table public.zonas enable row level security;
alter table public.inspecciones enable row level security;
alter table public.fotografias enable row level security;
alter table public.seguimientos enable row level security;

-- Profiles: users can see their own pending status; admin manages all profiles.
drop policy if exists perfiles_select_propios_o_admin on public.perfiles;
create policy perfiles_select_propios_o_admin on public.perfiles
for select to authenticated
using (id_usuario = auth.uid() or public.tiene_rol(array['administrador']));
drop policy if exists perfiles_admin_update on public.perfiles;
create policy perfiles_admin_update on public.perfiles
for update to authenticated
using (public.tiene_rol(array['administrador']) and id_usuario <> auth.uid())
with check (public.tiene_rol(array['administrador']));

-- Risk catalog: active users can consult categories; only admin can maintain catalog.
drop policy if exists tipos_riesgo_select_activos on public.tipos_riesgo;
create policy tipos_riesgo_select_activos on public.tipos_riesgo
for select to authenticated using (public.perfil_activo());
drop policy if exists tipos_riesgo_admin_insert on public.tipos_riesgo;
create policy tipos_riesgo_admin_insert on public.tipos_riesgo
for insert to authenticated with check (public.tiene_rol(array['administrador']));
drop policy if exists tipos_riesgo_admin_update on public.tipos_riesgo;
create policy tipos_riesgo_admin_update on public.tipos_riesgo
for update to authenticated using (public.tiene_rol(array['administrador'])) with check (public.tiene_rol(array['administrador']));

-- Zones: all active roles may read; admin and inspector may create; only admin edits/deactivates.
drop policy if exists zonas_select_activos on public.zonas;
create policy zonas_select_activos on public.zonas
for select to authenticated using (public.perfil_activo());
drop policy if exists zonas_insert_admin_inspector on public.zonas;
create policy zonas_insert_admin_inspector on public.zonas
for insert to authenticated with check (public.tiene_rol(array['administrador', 'inspector']));
drop policy if exists zonas_update_admin on public.zonas;
create policy zonas_update_admin on public.zonas
for update to authenticated using (public.tiene_rol(array['administrador'])) with check (public.tiene_rol(array['administrador']));

-- Inspections: read-only for consultant. Direct status updates are impossible because grants are column-limited.
drop policy if exists inspecciones_select_activos on public.inspecciones;
create policy inspecciones_select_activos on public.inspecciones
for select to authenticated using (public.perfil_activo());
drop policy if exists inspecciones_insert_admin_inspector on public.inspecciones;
create policy inspecciones_insert_admin_inspector on public.inspecciones
for insert to authenticated
with check (
  public.tiene_rol(array['administrador', 'inspector'])
  and id_usuario = auth.uid()
);
drop policy if exists inspecciones_update_admin_o_propias_pendientes on public.inspecciones;
create policy inspecciones_update_admin_o_propias_pendientes on public.inspecciones
for update to authenticated
using (
  public.tiene_rol(array['administrador'])
  or (public.tiene_rol(array['inspector']) and id_usuario = auth.uid() and estado = 'Pendiente')
)
with check (
  public.tiene_rol(array['administrador'])
  or (public.tiene_rol(array['inspector']) and id_usuario = auth.uid() and estado = 'Pendiente')
);

-- Photo metadata: only active users with access to the related inspection may read.
drop policy if exists fotografias_select_activos on public.fotografias;
create policy fotografias_select_activos on public.fotografias
for select to authenticated
using (public.perfil_activo());
drop policy if exists fotografias_insert_propietario on public.fotografias;
create policy fotografias_insert_propietario on public.fotografias
for insert to authenticated
with check (
  public.tiene_rol(array['administrador'])
  or (
    public.tiene_rol(array['inspector'])
    and exists (
      select 1 from public.inspecciones i
      where i.id_inspeccion = fotografias.id_inspeccion and i.id_usuario = auth.uid()
    )
  )
);

-- History is immutable from client-side table operations; only registrar_seguimiento() writes it.
drop policy if exists seguimientos_select_activos on public.seguimientos;
create policy seguimientos_select_activos on public.seguimientos
for select to authenticated using (public.perfil_activo());

-- Grants deliberately omit DELETE and direct client updates to inspection state/history.
grant usage on schema public to authenticated;
grant select on public.perfiles, public.tipos_riesgo, public.zonas, public.inspecciones, public.fotografias, public.seguimientos to authenticated;
grant update (nombre, rol, activo) on public.perfiles to authenticated;
grant insert, update on public.zonas to authenticated;
grant insert (id_zona, id_usuario, fecha_inspeccion, observaciones, nivel_atencion, recomendaciones) on public.inspecciones to authenticated;
grant update (id_zona, fecha_inspeccion, observaciones, nivel_atencion, recomendaciones) on public.inspecciones to authenticated;
grant insert (id_inspeccion, ruta_archivo, descripcion) on public.fotografias to authenticated;
grant usage, select on all sequences in schema public to authenticated;

